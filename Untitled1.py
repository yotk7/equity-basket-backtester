# Separate portfolio data from benchmark data
portfolio_data = data[tickers]
spy_data = data["SPY"]

# --- 1. PORTFOLIO CALCULATIONS ---
returns = portfolio_data.pct_change().dropna()
num_assets = len(returns.columns)
weights = [1.0 / num_assets] * num_assets

portfolio_return = returns.dot(weights)
portfolio_cumulative = (1 + portfolio_return).cumprod()

total_roi = portfolio_cumulative.iloc[-1] - 1
num_years = len(portfolio_return) / 252
cagr = (1 + total_roi) ** (1 / num_years) - 1
basket_volatility = portfolio_return.std() * (252**0.5)
sharpe_ratio = cagr / basket_volatility

# --- 2. S&P 500 BENCHMARK CALCULATIONS ---
spy_return = spy_data.pct_change().dropna()
spy_cumulative = (1 + spy_return).cumprod()
spy_total_roi = spy_cumulative.iloc[-1] - 1
spy_cagr = (1 + spy_total_roi) ** (1 / num_years) - 1
spy_volatility = spy_return.std() * (252**0.5)
spy_sharpe = spy_cagr / spy_volatility

